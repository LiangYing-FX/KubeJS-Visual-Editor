package dev.dsh.kjseditor.gen;

import dev.dsh.kjseditor.data.FieldType;
import dev.dsh.kjseditor.data.RecipeField;
import dev.dsh.kjseditor.data.RecipeKind;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;
import java.util.stream.Collectors;

public final class ScriptGen {
    /** Nested step lists, keyed by kindId|fieldKey. */
    public static final Map<String, List<RecipeEntry>> STEPS = new ConcurrentHashMap<>();
    /** Flat list values, keyed by kindId|fieldKey. */
    public static final Map<String, List<String>> LISTS = new ConcurrentHashMap<>();

    private ScriptGen() {
    }

    public static String key(RecipeKind kind, RecipeField field) {
        return kind.id() + "|" + field.key();
    }

    public static List<RecipeEntry> steps(RecipeKind kind, RecipeField field) {
        return STEPS.computeIfAbsent(key(kind, field), k -> new ArrayList<>());
    }

    public static List<String> list(RecipeKind kind, RecipeField field) {
        return LISTS.computeIfAbsent(key(kind, field), k -> new ArrayList<>());
    }

    public static String buildFile(List<RecipeEntry> entries) {
        StringBuilder sb = new StringBuilder();
        sb.append("// generated by KubeJS Visual Editor\n");
        sb.append("// entries: ").append(entries.size()).append("\n\n");
        sb.append("ServerEvents.recipes(event => {\n");
        for (int i = 0; i < entries.size(); i++) {
            RecipeEntry e = entries.get(i);
            String body = e.remove() ? buildRemove(e.kind(), e.values()) : buildBody(e.kind(), e.values());
            String[] lines = body.split("\n", -1);
            for (int l = 0; l < lines.length; l++) {
                sb.append("    ").append(lines[l]);
                // Terminate every statement explicitly instead of relying on ASI.
                if (l == lines.length - 1 && i < entries.size() - 1) {
                    sb.append(";");
                }
                sb.append("\n");
            }
        }
        sb.append("})\n");
        return sb.toString();
    }

    public static final String[] GRID_KEYS = {"a", "b", "c", "d", "e", "f", "g", "h", "i"};

    public static String buildBody(RecipeKind kind, Map<String, String> values) {
        if ("shaped".equals(kind.id())) {
            return shapedBody(kind, values);
        }
        if ("shapeless".equals(kind.id())) {
            return shapelessBody(kind, values);
        }
        if ("energizing".equals(kind.id()) && "powah".equals(kind.modId())) {
            return powahBody(kind, values);
        }
        String body = kind.template();
        for (RecipeField f : kind.fields()) {
            String raw = values.getOrDefault(f.key(), f.def());
            body = body.replace("{" + f.key() + "}", format(kind, f, raw));
        }
        return body;
    }

    private static String fieldValue(RecipeKind kind, Map<String, String> values, String key) {
        for (RecipeField f : kind.fields()) {
            if (f.key().equals(key)) {
                return values.getOrDefault(key, f.def());
            }
        }
        return "";
    }

    /**
     * Hand-written scripts use a specific multi-line layout and only list the keys that
     * actually appear in the pattern. Reproducing it exactly avoids surprises with
     * ASI / trailing punctuation and keeps the output diff-friendly.
     */
    private static String shapedBody(RecipeKind kind, Map<String, String> values) {
        String out = fieldValue(kind, values, "out");
        String count = fieldValue(kind, values, "count").trim();

        // Cells hold item ids; letters are assigned in reading order so that equal
        // items share a letter, exactly like a hand written pattern.
        java.util.Map<String, Character> letterOf = new java.util.LinkedHashMap<>();
        char next = 'A';
        String[] cells = new String[9];
        for (int i = 0; i < 9; i++) {
            String id = fieldValue(kind, values, GRID_KEYS[i]);
            cells[i] = id == null ? "" : id.trim();
            if (!cells[i].isEmpty() && !letterOf.containsKey(cells[i])) {
                letterOf.put(cells[i], next++);
            }
        }

        StringBuilder rows = new StringBuilder();
        for (int row = 0; row < 3; row++) {
            StringBuilder line = new StringBuilder();
            for (int col = 0; col < 3; col++) {
                String id = cells[row * 3 + col];
                line.append(id.isEmpty() ? ' ' : letterOf.get(id));
            }
            rows.append("        '").append(line).append("'");
            if (row < 2) {
                rows.append(",");
            }
            rows.append("\n");
        }

        StringBuilder sb = new StringBuilder();
        sb.append("event.shaped(\n");
        sb.append("    Item.of('").append(out.trim()).append("'");
        if (!count.isEmpty() && !"1".equals(count)) {
            sb.append(", ").append(count);
        }
        sb.append("),\n");
        sb.append("    [\n").append(rows).append("    ],\n");
        sb.append("    {\n");

        boolean first = true;
        for (java.util.Map.Entry<String, Character> e : letterOf.entrySet()) {
            if (!first) {
                sb.append(",\n");
            }
            sb.append("        ").append(e.getValue()).append(": '").append(e.getKey()).append("'");
            first = false;
        }
        sb.append("\n    }\n");
        sb.append(")");
        return sb.toString();
    }

    /** Powah's energizing orb takes up to six inputs; empty slots are dropped. */
    private static String powahBody(RecipeKind kind, Map<String, String> values) {
        List<String> ins = new ArrayList<>();
        for (int i = 1; i <= 6; i++) {
            String id = fieldValue(kind, values, "in" + i);
            if (id != null && !id.isBlank()) {
                ins.add("Item.of('" + id.trim() + "')");
            }
        }
        StringBuilder sb = new StringBuilder();
        sb.append("event.recipes.powah.energizing(\n");
        sb.append("    [\n");
        for (int i = 0; i < ins.size(); i++) {
            sb.append("        ").append(ins.get(i));
            if (i < ins.size() - 1) {
                sb.append(",");
            }
            sb.append("\n");
        }
        sb.append("    ],\n");
        sb.append("    Item.of('").append(fieldValue(kind, values, "out").trim()).append("'),\n");
        sb.append("    ").append(fieldValue(kind, values, "energy").trim()).append("\n");
        sb.append(")");
        return sb.toString();
    }

    /** Shapeless keeps one ingredient per line, like the hand-written form. */
    private static String shapelessBody(RecipeKind kind, Map<String, String> values) {
        String out = fieldValue(kind, values, "out");
        String count = fieldValue(kind, values, "count").trim();
        String key = kind.id() + "|inputs";
        java.util.List<String> items = LISTS.getOrDefault(key, java.util.List.of()).stream()
                .filter(s -> s != null && !s.isBlank())
                .toList();

        StringBuilder sb = new StringBuilder();
        sb.append("event.shapeless(\n");
        sb.append("    Item.of('").append(out.trim()).append("'");
        if (!count.isEmpty() && !"1".equals(count)) {
            sb.append(", ").append(count);
        }
        sb.append("),\n");
        sb.append("    [\n");
        for (int i = 0; i < items.size(); i++) {
            sb.append("        '").append(items.get(i).trim()).append("'");
            if (i < items.size() - 1) {
                sb.append(",");
            }
            sb.append("\n");
        }
        sb.append("    ]\n");
        sb.append(")");
        return sb.toString();
    }

    public static String buildRemove(RecipeKind kind, Map<String, String> values) {
        return "event.remove({ type: '" + kind.fullId() + "'" + removeFilter(kind, values) + " })";
    }

    private static String removeFilter(RecipeKind kind, Map<String, String> values) {
        for (RecipeField f : kind.fields()) {
            if (f.type() == FieldType.ITEM && f.key().startsWith("in")) {
                String v = values.getOrDefault(f.key(), f.def());
                if (v != null && !v.isBlank()) {
                    return ", input: '" + v.trim() + "'";
                }
            }
        }
        return "";
    }

    private static String format(RecipeKind kind, RecipeField f, String raw) {
        String rawValue = raw == null ? "" : raw;
        // TEXT/ENUM must keep leading/trailing spaces: shaped patterns like " A " depend on them.
        if (f.type() == FieldType.TEXT || f.type() == FieldType.ENUM) {
            return rawValue;
        }
        String s = rawValue.trim();
        return switch (f.type()) {
            case NUMBER -> s.isEmpty() ? "1" : s.replaceAll("[^0-9.-]", "");
            case BOOL -> "true".equalsIgnoreCase(s) ? "true" : "false";
            case ITEM -> "'" + s + "'";
            case ITEM_LIST -> toList(s);
            case FLUID -> toFluid(s);
            case NESTED -> toSteps(kind, f);
            case LIST -> toEntryList(kind, f);
            default -> rawValue;
        };
    }

    private static String toSteps(RecipeKind kind, RecipeField f) {
        List<RecipeEntry> list = STEPS.getOrDefault(key(kind, f), List.of());
        if (list.isEmpty()) {
            return "[]";
        }
        return list.stream()
                .map(e -> buildBody(e.kind(), e.values()))
                .collect(Collectors.joining(", "));
    }

    private static String toEntryList(RecipeKind kind, RecipeField f) {
        List<String> vals = LISTS.getOrDefault(key(kind, f), List.of());
        String tpl = f.itemTemplateOr("{v}");
        return vals.stream()
                .map(v -> tpl.replace("{v}", v))
                .collect(Collectors.joining(", ", "[", "]"));
    }

    private static String toList(String s) {
        if (s.isEmpty()) {
            return "[]";
        }
        String[] parts = s.split("[,\\n]");
        List<String> out = new ArrayList<>();
        for (String p : parts) {
            String t = p.trim();
            if (!t.isEmpty()) {
                out.add("'" + t + "'");
            }
        }
        return "[" + String.join(", ", out) + "]";
    }

    private static String toFluid(String s) {
        String id = s;
        String amount = "1000";
        int last = s.lastIndexOf(':');
        if (last > 0) {
            String maybe = s.substring(last + 1);
            if (maybe.matches("\\d+")) {
                id = s.substring(0, last);
                amount = maybe;
            }
        }
        return "Fluid.of('" + id + "', " + amount + ")";
    }
}
